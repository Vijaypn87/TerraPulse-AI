// Data provenance. Every number shown in the UI belongs to exactly one of these.
//   live  — returned by the configured backend (VITE_API_BASE_URL)
//   demo  — bundled demonstration data; NOT a real measurement
//   model — produced by a trained ML model served by the backend
export type DataSource = "live" | "demo" | "model";

export const SOURCE_META: Record<DataSource, { label: string; hint: string }> = {
  live: { label: "Live API", hint: "Returned by the configured TerraPulse backend." },
  demo: {
    label: "Demo data",
    hint: "Illustrative demonstration data. Not a real-time or verified measurement.",
  },
  model: { label: "ML prediction", hint: "Generated by a trained model served by the backend." },
};

type Listener = () => void;
const sources = new Map<string, DataSource>();
const listeners = new Set<Listener>();

export function setSource(key: string, s: DataSource) {
  if (sources.get(key) === s) return;
  sources.set(key, s);
  listeners.forEach((l) => l());
}

// Endpoints of a configured backend that failed to respond. Drives the "unavailable" notice.
const failed = new Set<string>();
let failedSnapshot = 0;
export function setFailed(key: string, isFailed: boolean) {
  if (failed.has(key) === isFailed) return;
  if (isFailed) failed.add(key);
  else failed.delete(key);
  failedSnapshot = failed.size;
  listeners.forEach((l) => l());
}
export function getFailedCount() {
  return failedSnapshot;
}

export function getSource(key: string): DataSource {
  return sources.get(key) ?? "demo";
}
export function subscribeSources(l: Listener) {
  listeners.add(l);
  return () => {
    listeners.delete(l);
  };
}
